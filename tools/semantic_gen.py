def gen_int32_shell_shift(seed):
    """int32(int64(x) >> s) with s > 32: the shift arm must honor the 64-bit
    operand width (a 32-bit asr silently reduces the amount mod 32) (D1 form)."""
    rng = rng_for("int32_shell_shift", seed)
    want = rng.span(3, 250)
    shift = rng.span(33, 40)
    low = rng.span(0, (1 << 20) - 1)
    base = (want << shift) | low
    nested = rng.below(2) == 1
    lines = [
        "fn main(): int32 =",
        "    var x: int64 = Int64(%d)" % base,
    ]
    if nested:
        s1 = shift // 2 + 1
        s2 = shift - s1
        # recompute so the composed shift lands exactly on `want`
        lines.append("    let y: int32 = int32((x >> %d) >> %d)" % (s1, s2))
        lines.append("    return y")
        note = ("Int32 壳移位(嵌套): int32((x>>%d)>>%d) 合成 64 位右移 %d, 期望 rc=%d; "
                "形态源=D1 标量移位臂硬编 i32 Asr 不看操作数宽度" % (s1, s2, shift, want))
    else:
        lines.append("    let y: int32 = int32(x >> %d)" % shift)
        lines.append("    return y")
        note = ("Int32 壳移位: int32(Int64(%d) >> %d) 期望 rc=%d; "
                "形态源=D1 (32 位 asr 会把移位量 mod 32, 本族移位量全部 >32)" % (base, shift, want))
    return BANNER + "\n".join(lines) + "\n", {"expectRc": want}, note


