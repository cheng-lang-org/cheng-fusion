def gen_str_global_call_rhs(seed):
    """str global assigned from call RHS, reassigned, read back (I1/I3/B3 form)."""
    rng = rng_for("str_global_call_rhs", seed)
    length = rng.span(3, 9)
    cycles = rng.span(2, 3)
    text = word(rng, length)
    lines = [
        "var gCache: str",
        "",
        "fn makeStr(): str =",
        '    return "%s"' % text,
        "",
        "fn main(): int32 =",
    ]
    for i in range(cycles):
        lines.append("    gCache = makeStr()")
        lines.append("    let v%d = gCache" % i)
        lines.append("    if len(v%d) != %d:" % (i, length))
        lines.append("        return %d" % (90 + i))
    lines.append('    if v0 != "%s":' % text)
    lines.append("        return 95")
    lines.append("    return %s" % " + ".join("len(v%d)" % i for i in range(cycles)))
    expect = cycles * length
    note = ("str 全局 call-RHS: %d 次 `gCache = makeStr()` 写+全局读回, "
            "期望 rc=%d (cycles*len); 形态源=I1/I3 LocalStrTag 臂 + B3 模块级 str 缓存 idiom" % (cycles, expect))
    return BANNER + "\n".join(lines) + "\n", {"expectRc": expect}, note


def gen_slot_dedup_chain(seed):
    """if-guarded tail call at return position; global counter makes any
    double physical execution directly observable in the exit code (T52 form)."""
    rng = rng_for("slot_dedup_chain", seed)
    k = rng.span(2, 9)
    n = rng.span(10, 60)
    threshold = rng.span(0, n - 1)
    chain = rng.span(1, 3)
    lines = [
        "var gCalls: int32",
        "",
        "fn helper(x: int32): int32 =",
        "    gCalls = gCalls + 1",
        "    return x + %d" % k,
        "",
        "fn bridge(v: int32): int32 =",
        "    if v > %d:" % threshold,
        "        return helper(v)",
        "    return v",
        "",
        "fn main(): int32 =",
    ]
    for i in range(chain):
        lines.append("    let r%d = bridge(%d)" % (i, n + i))
        lines.append("    if r%d != %d:" % (i, n + i + k))
        lines.append("        return %d" % (90 + i))
    lines.append("    return gCalls")
    note = ("槽支配 dedup 链: %d 次 bridge 尾部调用, helper 物理执行计数经全局可观测, "
            "期望 rc=%d (恰好 %d 次); 形态源=T52 return<call> fact dedup + I2 CFOS 槽支配" % (chain, chain, chain))
    return BANNER + "\n".join(lines) + "\n", {"expectRc": chain}, note


