def build(root, out_rel, families, seeds):
    """Returns {relpath: bytes} for the whole fixture set + matrix.json."""
    files = {}
    entries = []
    for family in families:
        gen = GENS[family]
        for seed in range(1, seeds + 1):
            source, contract, note = gen(seed)
            name = "%s_s%d" % (family, seed)
            rel = "%s/%s.cheng" % (family, name)
            files[rel] = source.encode("utf-8")
            entry = {
                "name": name,
                "tags": ["generated", "family:%s" % family, "form:%s" % FORM_TAG[family], "seed:%d" % seed],
                "fixture": rel,
            }
            entry.update(contract)
            entry["note"] = note
            entries.append(entry)
    matrix = {
        "defaultRoot": root,
        "generatedBy": "tools/semantic_gen.py (deterministic; regenerate with same --root/--seeds to reproduce byte-identical output)",
        "entries": entries,
    }
    text = json.dumps(matrix, ensure_ascii=False, indent=2) + "\n"
    files["matrix.json"] = text.encode("utf-8")
    return files


def main(argv):
    parser = argparse.ArgumentParser(description="bounded semantic combination generator for Cheng fixtures")
    parser.add_argument("--root", required=True, help="absolute Cheng tree root; written into matrix.json defaultRoot (never pinned by the generator)")
    parser.add_argument("--out", default="fixtures/semantic", help="output dir, relative to cheng-fusion package root (default fixtures/semantic)")
    parser.add_argument("--seeds", type=int, default=3, help="seeds per family, seeds are 1..N (default 3)")
    parser.add_argument("--families", default="all", help="comma list, or 'all' (default)")
    parser.add_argument("--check", action="store_true", help="regenerate in memory and byte-compare against --out; rc=1 on any drift, writes nothing")
    args = parser.parse_args(argv)

    root = os.path.realpath(args.root)
    if not os.path.isdir(root):
        parser.error("--root is not a directory: %s" % root)
    if args.seeds < 1:
        parser.error("--seeds must be >= 1")
    if args.families == "all":
        families = list(FAMILIES)
    else:
        families = args.families.split(",")
        unknown = [f for f in families if f not in GENS]
        if unknown:
            parser.error("unknown families: %s (known: %s)" % (",".join(unknown), ",".join(FAMILIES)))

    package_root = os.path.realpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    out_dir = args.out if os.path.isabs(args.out) else os.path.join(package_root, args.out)

    files = build(root, args.out, families, args.seeds)

    if args.check:
        drift = []
        for rel in sorted(files):
            path = os.path.join(out_dir, rel)
            if not os.path.isfile(path):
                drift.append("missing: %s" % rel)
                continue
            with open(path, "rb") as fh:
                if fh.read() != files[rel]:
                    drift.append("drifted: %s" % rel)
        extra = []
        managed_dirs = set(FAMILIES)
        for dirpath, _dirnames, filenames in os.walk(out_dir):
            for fn in filenames:
                rel = os.path.relpath(os.path.join(dirpath, fn), out_dir)
                # 只审计生成器自管范围(family 目录与 matrix.json); 其他生成器
                # (如 grammar_corpus_gen.ts)共享 fixtures/semantic, 不算漂移。
                if rel == "matrix.json" or rel.split(os.sep)[0] in managed_dirs:
                    if rel not in files and not fn.startswith("."):
                        extra.append("extra: %s" % rel)
        problems = drift + extra
        if problems:
            sys.stderr.write("semantic_gen --check FAIL (%d):\n%s\n" % (len(problems), "\n".join(problems)))
            return 1
        sys.stdout.write("semantic_gen --check OK: %d files byte-identical (root=%s seeds=%d families=%d)\n" % (len(files), root, args.seeds, len(families)))
        return 0

    written = []
    for rel in sorted(files):
        path = os.path.join(out_dir, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as fh:
            fh.write(files[rel])
        written.append(rel)
    sys.stdout.write("semantic_gen: wrote %d files under %s (root=%s, %d families x %d seeds = %d fixtures)\n"
                     % (len(written), out_dir, root, len(families), args.seeds, len(written) - 1))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
