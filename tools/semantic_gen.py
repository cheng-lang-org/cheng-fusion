def gen_ref_seq_field(seed):
    """struct carrying a T[] field between two scalars: field offsets must treat
    the seq as a 16B inline header, not an 8B ref pointer (W2D form)."""
    rng = rng_for("ref_seq_field", seed)
    head = rng.span(3, 60)
    tail = rng.span(3, 60)
    nitems = rng.span(1, 3)
    tags = [rng.span(1, 9) for _ in range(nitems)]
    weights = [rng.span(1, 9) for _ in range(nitems)]
    lines = [
        "type",
        "    Sym =",
        "        tag: int32",
        "        weight: int32",
        "",
        "    Holder =",
        "        head: int32",
        "        items: Sym[]",
        "        tail: int32",
        "",
        "fn main(): int32 =",
        "    var h: Holder",
        "    h.head = %d" % head,
        "    h.tail = %d" % tail,
    ]
    for i in range(nitems):
        lines.append("    let s%d = Sym(tag: %d, weight: %d)" % (i, tags[i], weights[i]))
        lines.append("    add(h.items, s%d)" % i)
    checks = [("h.head", head, 81), ("h.tail", tail, 82), ("h.items.len", nitems, 83)]
    for expr, want, rc in checks:
        lines.append("    if %s != %d:" % (expr, want))
        lines.append("        return %d" % rc)
    for i in range(nitems):
        lines.append("    if h.items[%d].tag != %d:" % (i, tags[i]))
        lines.append("        return %d" % (84 + i * 2))
        lines.append("    if h.items[%d].weight != %d:" % (i, weights[i]))
        lines.append("        return %d" % (85 + i * 2))
    expect = head + tail
    lines.append("    return h.head + h.tail")
    note = ("ref-seq 字段: Holder{head, items:Sym[], tail} 偏移完整性, %d 元素入列后标量字段不得错位, "
            "期望 rc=%d; 形态源=W2D TypedExprIrAppendObjectTypeLayoutFromContext 把 Sym[] 错注 8B ref (正解 16B 内联 seq 头)" % (nitems, expect))
    return BANNER + "\n".join(lines) + "\n", {"expectRc": expect}, note


