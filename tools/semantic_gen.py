def fnv1a64(text):
    h = 1469598103934665603
    for ch in text.encode("utf-8"):
        h ^= ch
        h = (h * 1099511628211) & MASK64
    return h


class Rng(object):
    """xorshift64* — stable across python versions and machines."""

    def __init__(self, seed):
        self.state = (seed ^ 0x9E3779B97F4A7C15) & MASK64 or 0x2545F4914F6CDD1D

    def next64(self):
        x = self.state
        x ^= (x >> 12) & MASK64
        x ^= (x << 25) & MASK64
        x ^= (x >> 27) & MASK64
        self.state = x & MASK64
        return (self.state * 2685821657736338717) & MASK64

    def below(self, n):
        return self.next64() % n

    def span(self, lo, hi):
        return lo + self.below(hi - lo + 1)


def rng_for(family, seed):
    return Rng((fnv1a64(family) << 1) ^ (seed * 0x100000001B3))


def word(rng, length):
    # lowercase letters only; fixture string literals stay pointer-safe
    return "".join(chr(ord("a") + rng.below(26)) for _ in range(length))


