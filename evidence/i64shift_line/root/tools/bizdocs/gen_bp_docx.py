# ---------- 全局样式 ----------
def set_font(style, name_cn, size, color=INK, bold=False):
    style.font.name = "Times New Roman"
    style.font.size = Pt(size)
    style.font.bold = bold
    style.font.color.rgb = color
    style._element.rPr.rFonts.set(qn("w:eastAsia"), name_cn)

normal = doc.styles["Normal"]
set_font(normal, "宋体", 12)  # 小四
normal.paragraph_format.line_spacing = 1.4
normal.paragraph_format.space_after = Pt(6)

for name, size, color, bold, cn in [
    ("Heading 1", 16, INDIGO, True, "黑体"),
    ("Heading 2", 14, INK, True, "黑体"),
    ("Heading 3", 12, GOLD_D, True, "黑体"),
]:
    st = doc.styles[name]
    set_font(st, cn, size, color, bold)
    st.paragraph_format.space_before = Pt(14 if name == "Heading 1" else 10)
    st.paragraph_format.space_after = Pt(6)

for sec in doc.sections:
    sec.left_margin = Cm(2.4); sec.right_margin = Cm(2.4)
    sec.top_margin = Cm(2.4); sec.bottom_margin = Cm(2.2)

def para(text, style=None, size=None, color=None, bold=False, align=None,
         space_after=None):
    p = doc.add_paragraph(text, style=style)
    for run in p.runs:
        if size: run.font.size = Pt(size)
        if color: run.font.color.rgb = color
        run.font.bold = bold or run.font.bold
    if align is not None: p.alignment = align
    if space_after is not None: p.paragraph_format.space_after = Pt(space_after)
    return p

def h1(t): return doc.add_paragraph(t, style="Heading 1")
def h2(t): return doc.add_paragraph(t, style="Heading 2")
def h3(t): return doc.add_paragraph(t, style="Heading 3")
def body(t): return para(t)
def bullet(t):
    p = doc.add_paragraph(t, style="List Bullet")
    p.paragraph_format.space_after = Pt(3)
    return p

def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear"); shd.set(qn("w:fill"), hexcolor)
    tcPr.append(shd)

def table(rows, widths_cm, header=True):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(rows):
        for j, text in enumerate(row):
            cell = t.cell(i, j)
            cell.width = Cm(widths_cm[j])
            cell.text = ""
            p = cell.paragraphs[0]
            run = p.add_run(text)
            run.font.size = Pt(12)  # 小四
            run.font.name = "Times New Roman"
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
            p.paragraph_format.space_after = Pt(2)
            if header and i == 0:
                run.font.bold = True
                run._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")
                shade(cell, "F4F3EE")
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

